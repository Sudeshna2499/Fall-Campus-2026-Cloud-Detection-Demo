"""Ground segment: fit the brightness-rule threshold, train the tiny 5-8-3 MLP, export model.h.

Run:  python3 train_model.py
Outputs: model.npz (for --sim) and obc_cloud/model.h (what gets "uplinked" to the board).
"""
import numpy as np
from cloud_sim import (CLASSES, NT, make_scene, dataset, forward, rule_cloud, DISCARD_P)

rng = np.random.default_rng(7)
SCENE_SEED = 3


def fit_threshold(m, y):
    best = (0, 0)
    for t in np.arange(0.15, 0.6, 0.005):
        pred = m > t
        tp = (pred & (y == 2)).sum(); fp = (pred & (y != 2)).sum(); fn = (~pred & (y == 2)).sum()
        f1 = 2 * tp / max(2 * tp + fp + fn, 1)
        if f1 > best[0]:
            best = (f1, float(t))
    return best[1]


def train(X, y, hidden=8, epochs=1500, lr=0.02):
    n, d = X.shape
    k = 3
    p = {"W1": rng.normal(0, np.sqrt(2 / d), (d, hidden)).astype(np.float32),
         "b1": np.zeros(hidden, np.float32),
         "W2": rng.normal(0, np.sqrt(2 / hidden), (hidden, k)).astype(np.float32),
         "b2": np.zeros(k, np.float32)}
    Y = np.eye(k, dtype=np.float32)[y]
    m = {key: np.zeros_like(v) for key, v in p.items()}
    v2 = {key: np.zeros_like(v) for key, v in p.items()}
    for ep in range(1, epochs + 1):
        h = np.maximum(0, X @ p["W1"] + p["b1"])
        z = h @ p["W2"] + p["b2"]
        z -= z.max(1, keepdims=True)
        pr = np.exp(z); pr /= pr.sum(1, keepdims=True)
        dz = (pr - Y) / n
        g = {"W2": h.T @ dz, "b2": dz.sum(0)}
        dh = dz @ p["W2"].T; dh[h <= 0] = 0
        g["W1"] = X.T @ dh; g["b1"] = dh.sum(0)
        for key in p:
            m[key] = 0.9 * m[key] + 0.1 * g[key]
            v2[key] = 0.999 * v2[key] + 0.001 * g[key] ** 2
            p[key] -= (lr * (m[key] / (1 - 0.9 ** ep)) / (np.sqrt(v2[key] / (1 - 0.999 ** ep)) + 1e-8)).astype(np.float32)
    return p


def arr(name, a, ctype="float", conv=lambda v: f"{v:.7e}f"):
    a = np.asarray(a).ravel()
    return f"const {ctype} {name}[{a.size}] PROGMEM = {{{', '.join(conv(v) for v in a)}}};\n"


def export_header(p, m_thr, path):
    d, h = p["W1"].shape
    surf, v, alpha = make_scene(SCENE_SEED)
    with open(path, "w") as f:
        f.write("// Auto-generated by train_model.py -- do not edit.\n#pragma once\n")
        f.write(f"#define N_IN {d}\n#define N_HID {h}\n#define N_OUT 3\n")
        f.write(f"#define RULE_M_THR {m_thr:.4f}f   // fitted brightness threshold for the simple rule\n")
        f.write(f"#define DISCARD_P {DISCARD_P}f\n#define SCENE_TILES {NT}\n")
        f.write(arr("W1", p["W1"].T)); f.write(arr("B1", p["b1"]))
        f.write(arr("W2", p["W2"].T)); f.write(arr("B2", p["b2"]))
        f.write("// demo scene, one entry per tile: surface (0 land, 1 sea, 2 sand), soil % and cloud %\n")
        f.write(arr("SC_SURF", surf, "uint8_t", lambda x: str(int(x))))
        f.write(arr("SC_SOIL", np.round(v * 100), "uint8_t", lambda x: str(int(x))))
        f.write(arr("SC_CLOUD", np.round(alpha * 100), "uint8_t", lambda x: str(int(x))))


def report(name, y, cloud_pred):
    c = y == 2
    tp = (cloud_pred & c).sum(); fn = (~cloud_pred & c).sum()
    lost = (cloud_pred & ~c).sum()
    print(f"  {name:<22} cloud caught {tp / max(tp + fn, 1):.3f}   clear tiles wrongly discarded {lost / max((~c).sum(), 1):.3f}")


if __name__ == "__main__":
    X, m, y = dataset(30000, rng)
    m_thr = fit_threshold(m, y)
    print(f"fitted brightness threshold: mean brightness > {m_thr:.3f} means cloud")
    p = train(X, y)
    Xt, mt, yt = dataset(10000, np.random.default_rng(99))
    pr = forward(Xt, p)
    print("held-out tiles:")
    report("brightness rule", yt, rule_cloud(mt, m_thr))
    report("MLP (discard if P>%.2f)" % DISCARD_P, yt, pr[:, 2] > DISCARD_P)
    print("MLP accuracy (3 classes):", (pr.argmax(1) == yt).mean().round(3))
    np.savez("model.npz", m_thr=m_thr, **p)
    export_header(p, m_thr, "obc_cloud/model.h")
    n = sum(v.size for v in p.values())
    print(f"saved model.npz and obc_cloud/model.h ({n} parameters, {n * 4} bytes as float32)")
