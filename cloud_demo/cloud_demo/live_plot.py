"""Live graphs for the on-board cloud-screening demo.

  python3 live_plot.py --port /dev/ttyACM0     # Arduino (Windows: COM4)
  python3 live_plot.py --sim                   # same logic in Python, no hardware
  python3 live_plot.py --sim --save demo.png   # headless snapshot of two scenes
"""
import argparse
import numpy as np
import matplotlib
from cloud_sim import (GRID_W, GRID_H, NT, RAW_TILE_BYTES, FLAG_BYTES, DISCARD_P, UNSURE_P, make_scene,
                       make_tiles, tile_stats, norm_features, forward, load_params, truth_label)

# status codes for the maps
NONE, SENT_OK, DROP_OK, LOST, WASTED = 0, 1, 2, 3, 4
COLORS = ["#ECE8DD", "#8BC6A0", "#B5BBC9", "#D1342F", "#F2A33A"]
LABELS = ["not seen yet", "clear, sent", "cloud, discarded", "clear tile discarded (data lost)", "cloud sent (bytes wasted)"]


LOG_COLS = ["idx", "surf", "cloud_pct", "truth", "m", "s", "w", "r", "g", "b", "rule", "pcloud", "send", "raw_bytes", "tx_bytes"]


def status(truth, discard):
    cloud = truth == 2
    if discard:
        return DROP_OK if cloud else LOST
    return WASTED if cloud else SENT_OK

# creating a simulation of what a camera would record as images for the model to analyse
def sim_source(params, m_thr):
    seed = 3
    rng = np.random.default_rng(5)
    raw = tx = 0
    while True:
        surf, v, alpha = make_scene(seed)
        px_all = make_tiles(surf, v, alpha, rng)
        m, s, w, ndvi, nir, r, g, b = tile_stats(px_all)
        P = forward(norm_features(m, s, w, ndvi, nir), params)
        raw = tx = 0
        for i in range(NT):
            pc = P[i, 2]
            send = 0 if pc > DISCARD_P else 1
            raw += RAW_TILE_BYTES; tx += FLAG_BYTES + (RAW_TILE_BYTES if send else 0)
            yield dict(idx=i, surf=int(surf[i]), cpct=int(round(alpha[i] * 100)), truth=int(truth_label(surf[i], alpha[i])),
                       m=m[i], s=s[i], w=w[i], rgb=(r[i], g[i], b[i]), rule=2 if m[i] > m_thr else 0,
                       pc=pc, send=send, raw=raw, tx=tx)
        seed = 3 if seed >= 60 else seed + 1
        

# function to parse the data generated by the Arduino
def serial_source(port):
    import serial
    ser = serial.Serial(port, 115200, timeout=2)
    while True:
        line = ser.readline().decode(errors="ignore").strip()
        if not line or line.startswith("#"):
            continue
        try:
            v = line.split(",")
            yield dict(idx=int(v[0]), surf=int(v[1]), cpct=int(v[2]), truth=int(v[3]), m=float(v[4]), s=float(v[5]),
                       w=float(v[6]), rgb=(float(v[9]), float(v[10]), float(v[11])), rule=int(v[12]),
                       pc=float(v[14]), send=int(v[15]), raw=int(v[16]), tx=int(v[17]))
        except (ValueError, IndexError):
            continue


class Board:
    def __init__(self, m_thr):
        self.m_thr = m_thr
        self.tot = dict(cloud=0, caught_rule=0, caught_mlp=0, clear=0, lost_rule=0, lost_mlp=0)
        self.new_scene()
        self.pts = []

    def new_scene(self):
        self.rgb = np.zeros((NT, 3)); self.st_rule = np.zeros(NT, int); self.st_mlp = np.zeros(NT, int)
        self.unsure = np.zeros(NT, bool); self.raw = []; self.tx = []

    def add(self, r):
        i = r["idx"]
        if i == 0 and self.raw:
            self.new_scene()
        c = np.clip(np.array(r["rgb"]) * 1.9, 0, 1) ** 0.6
        self.rgb[i] = c
        d_rule = r["rule"] == 2; d_mlp = r["send"] == 0
        self.st_rule[i] = status(r["truth"], d_rule); self.st_mlp[i] = status(r["truth"], d_mlp)
        self.unsure[i] = (not d_mlp) and r["pc"] > UNSURE_P
        self.raw.append(r["raw"]); self.tx.append(r["tx"])
        t = self.tot
        if r["truth"] == 2:
            t["cloud"] += 1; t["caught_rule"] += d_rule; t["caught_mlp"] += d_mlp
        else:
            t["clear"] += 1; t["lost_rule"] += d_rule; t["lost_mlp"] += d_mlp
        self.pts.append((r["m"], r["w"], r["truth"]))
        self.pts = self.pts[-400:]


# function to plot all the dynamic graphs in the live plot
def draw(axs, B):
    cmap = matplotlib.colors.ListedColormap(COLORS)
    for ax in axs.ravel():
        ax.clear()
    grid = lambda a: a.reshape(GRID_H, GRID_W)
    axs[0, 0].imshow(B.rgb.reshape(GRID_H, GRID_W, 3), interpolation="nearest")
    axs[0, 0].set_title("what the satellite sees (synthetic tiles)", fontsize=9)
    axs[0, 1].imshow(grid(B.st_rule), cmap=cmap, vmin=0, vmax=4, interpolation="nearest")
    axs[0, 1].set_title("simple brightness rule", fontsize=9)
    axs[0, 2].imshow(grid(B.st_mlp), cmap=cmap, vmin=0, vmax=4, interpolation="nearest")
    ys, xs = np.where(grid(B.unsure))
    axs[0, 2].scatter(xs, ys, marker="o", s=40, facecolors="none", edgecolors="k", linewidths=1)
    axs[0, 2].set_title("on-board MLP (ring = sent but unsure)", fontsize=9)
    for ax in axs[0]:
        ax.set_xticks([]); ax.set_yticks([])
    # features
    ax = axs[1, 0]
    col = {0: "#4C9F70", 1: "#3E6FB0", 2: "#8A8F9E"}
    for k, name in enumerate(["clear land", "clear sea", "cloud"]):
        pk = [(a, b) for a, b, t in B.pts if t == k]
        if pk:
            ax.scatter(*zip(*pk), s=10, color=col[k], label=name)
    ax.axvline(B.m_thr, color="k", ls="--", lw=1)
    ax.text(B.m_thr + 0.005, 0.92, "rule", fontsize=8)
    ax.set_xlabel("mean brightness"); ax.set_ylabel("whiteness (low = grey/white)")
    ax.set_ylim(0, 1.05); ax.legend(fontsize=7, loc="upper right"); ax.set_title("two of the five features", fontsize=9)
    # bytes
    ax = axs[1, 1]
    if B.raw:
        ax.plot(B.raw, color="#8A8F9E", label="send every tile")
        ax.plot(B.tx, color="#0B6E78", lw=2, label="send only what the MLP keeps")
        ax.set_title(f"bytes to downlink: {100 * B.tx[-1] / B.raw[-1]:.0f}% of raw", fontsize=9)
    ax.set_xlabel("tiles processed"); ax.set_ylabel("cumulative bytes"); ax.legend(fontsize=7, loc="upper left")
    # scoreboard
    ax = axs[1, 2]; ax.axis("off")
    t = B.tot
    cr = lambda k: t[k] / max(t["cloud"], 1); lr = lambda k: t[k] / max(t["clear"], 1)
    txt = (f"Tiles so far: {t['cloud']} cloudy, {t['clear']} clear\n\n"
           f"                    brightness rule     MLP\n"
           f"cloud discarded      {cr('caught_rule'):6.1%}         {cr('caught_mlp'):6.1%}\n"
           f"clear tiles lost     {t['lost_rule']:>3d} ({lr('lost_rule'):.1%})      {t['lost_mlp']:>3d} ({lr('lost_mlp'):.1%})\n\n"
           f"A lost clear tile is data that never\nreaches the ground.\n\n"
           f"Synthetic tiles, not a validated result.")
    ax.text(0, 1, txt, va="top", family="monospace", fontsize=9)
    handles = [matplotlib.patches.Patch(color=COLORS[i], label=LABELS[i]) for i in range(1, 5)]
    axs[1, 2].legend(handles=handles, fontsize=7, loc="lower left")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--port"); ap.add_argument("--sim", action="store_true"); ap.add_argument("--save")
    ap.add_argument("--log", help="also write every tile to this CSV (feed it to plot_results.py)")
    a = ap.parse_args()
    if a.save:
        matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.animation import FuncAnimation
    params, m_thr = load_params()
    src = sim_source(params, m_thr) if (a.sim or not a.port) else serial_source(a.port)
    B = Board(m_thr)
    logf = None
    if a.log:
        import csv
        logf = open(a.log, "w", newline="")
        logw = csv.writer(logf)
        logw.writerow(LOG_COLS)
        _src = src

        def src_logged():
            for r in _src:
                logw.writerow([r["idx"], r["surf"], r["cpct"], r["truth"], f"{r['m']:.4f}", f"{r['s']:.4f}", f"{r['w']:.4f}",
                               *[f"{c:.4f}" for c in r["rgb"]], r["rule"], f"{r['pc']:.4f}", r["send"], r["raw"], r["tx"]])
                logf.flush()
                yield r
        src = src_logged()
    fig, axs = plt.subplots(2, 3, figsize=(13, 7))
    fig.suptitle("On-board cloud screening on a CubeSat OBC: discard cloudy tiles before downlink", fontsize=12)
    if a.save:
        for _ in range(NT):
            B.add(next(src))
        draw(axs, B); fig.tight_layout(rect=(0, 0, 1, 0.95)); fig.savefig(a.save, dpi=110); print("saved", a.save)
        return

    def step(_):
        for _ in range(3):
            B.add(next(src))
        draw(axs, B)
    ani = FuncAnimation(fig, step, interval=120, cache_frame_data=False)
    fig.tight_layout(rect=(0, 0, 1, 0.95)); plt.show()


if __name__ == "__main__":
    main()
